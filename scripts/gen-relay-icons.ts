/**
 * Write the few Phosphor (regular) icons the Relay theme uses into a small
 * module, so the client bundle doesn't ship the whole icon set. Includes the
 * content icons mapped in theme-relay/icon-map.ts, plus the brand marks
 * Phosphor lacks (stored as "brand:<name>" from Font Awesome Brands).
 *
 * Run: bun run scripts/gen-relay-icons.ts
 */
