import ph from "@iconify-json/ph/icons.json";
import faBrands from "@iconify-json/fa6-brands/icons.json";
import { PHOSPHOR, BRANDS } from "../.vitepress/theme-relay/icon-map";
import { getIconData, iconToSVG } from "@iconify/utils";

const NAMES = [
  "arrow-up-right",
  "arrow-right",
  "arrow-left",
  "list",
  "x",
  "info",
  "lightbulb",
  "warning",
  "sun",
  "moon",
  "link-simple",
  "download-simple",
  "caret-left",
  "caret-right",
  // Sidebar group headings (relay-nav.ts).
  "flag",
  "link-simple",
  "users-three",
  "chart-line",
  "apple-logo",
  "arrows-clockwise",
  "credit-card",
  "lifebuoy",
  "code",
  "flask",
  "plugs-connected",
  "webhooks-logo",
  "megaphone",
  "chart-bar",
  "shopping-cart",
  "handshake",
  "plugs",
  "briefcase",
  // Copy page button.
  "copy",
  "check",
  // Ask AI panel.
  "sparkle",
  "stop",
  "arrow-down",
  "magnifying-glass",
  "file-text",
  "note-pencil",
  "quotes",
  "thumbs-up",
  "thumbs-down",
  "caret-down",
  "sidebar-simple",
  "arrows-in-simple",
];

const icons: Record<string, { viewBox: string; body: string }> = {};
for (const name of new Set([...NAMES, ...Object.values(PHOSPHOR)])) {
  const data = getIconData(ph as any, name);
  if (!data) throw new Error(`Unknown Phosphor icon: ${name}`);
  const svg = iconToSVG(data);
  icons[name] = { viewBox: svg.attributes.viewBox, body: svg.body };
}

for (const name of BRANDS) {
  const data = getIconData(faBrands as any, name);
  if (!data) throw new Error(`Unknown brand icon: ${name}`);
  const svg = iconToSVG(data);
  icons[`brand:${name}`] = { viewBox: svg.attributes.viewBox, body: svg.body };
}

writeFileSync(
  ".vitepress/theme-relay/icons.ts",
  `// Generated by scripts/gen-relay-icons.ts from @iconify-json/ph (+ a few fa6-brands marks). Do not edit.\n` +
    `export const icons: Record<string, { viewBox: string; body: string }> = ${JSON.stringify(icons, null, 2)};\n`
);
console.log(`Wrote ${Object.keys(icons).length} icons.`);

// VitePress's own controls (search, outline, pager, appearance, external
// links, code copy) draw Lucide icons through CSS variables. Point them at the
// Phosphor equivalents.
const CHROME: [selector: string, icon: string][] = [
  [".vpi-align-left", "text-align-left"],
  [".vpi-arrow-right,\n.vpi-arrow-down,\n.vpi-arrow-left,\n.vpi-arrow-up", "arrow-right"],
  [".vpi-chevron-right,\n.vpi-chevron-down,\n.vpi-chevron-left,\n.vpi-chevron-up", "caret-right"],
  [".vpi-corner-down-left", "arrow-elbow-down-left"],
  [".vpi-delete", "backspace"],
  [".vpi-heart", "heart"],
  [".vpi-languages", "translate"],
  [".vpi-layout-list", "list-bullets"],
  [".vpi-moon", "moon"],
  [".vpi-more-horizontal", "dots-three"],
  [".vpi-plus", "plus"],
  [".vpi-search", "magnifying-glass"],
  [".vpi-square-pen", "pencil-simple"],
  [".vpi-sun", "sun"],
  [
    ":is(.vp-external-link-icon, .vp-doc a[href*='://'], .vp-doc a[target='_blank']):not(:is(.no-icon, svg a, :has(img, svg)))::after",
    "arrow-up-right",
  ],
];

function dataUri(name: string, color = "#000") {
  const data = getIconData(ph as any, name);
  if (!data) throw new Error(`Unknown Phosphor icon: ${name}`);
  const { attributes, body } = iconToSVG(data);
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='${attributes.viewBox}'>${body
    .replaceAll("currentColor", color)
    .replaceAll('"', "'")}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%27/g, "'")}")`;
}

let css = "/* Generated by scripts/gen-relay-icons.ts. Do not edit. Phosphor (MIT) in place of VitePress's Lucide icons. */\n";
for (const [selector, name] of CHROME) css += `${selector} {\n  --icon: ${dataUri(name)};\n}\n`;
css += `:root {\n  --vp-icon-copy: ${dataUri("copy", "rgba(128,128,128,1)")};\n  --vp-icon-copied: ${dataUri("check", "rgba(128,128,128,1)")};\n}\n`;
writeFileSync(".vitepress/theme-relay/chrome-icons.css", css);
console.log(`Wrote ${CHROME.length + 2} chrome icon overrides.`);
